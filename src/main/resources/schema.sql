-- PostgreSQL 데이터베이스 스키마
-- 카운트다운 타이머 애플리케이션용

-- 기존 테이블 삭제 (존재하는 경우)
DROP TABLE IF EXISTS TIMESTAMP CASCADE;
DROP TABLE IF EXISTS TIMER CASCADE;

-- 타이머 테이블 생성
CREATE TABLE TIMER (
    TIMER_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    TARGET_TIME TIMESTAMP NOT NULL,
    OWNER_ID VARCHAR(255) NOT NULL,
    IS_EXPIRED BOOLEAN NOT NULL DEFAULT FALSE,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 타임스탬프 테이블 생성
CREATE TABLE TIMESTAMP (
    ID BIGSERIAL PRIMARY KEY,
    TIMER_ID VARCHAR(36) NOT NULL,
    REMAINING_TIME VARCHAR(100) NOT NULL,
    CAPTURED_TIME TIMESTAMP NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_TIMESTAMPS_TIMER_ID
        FOREIGN KEY (TIMER_ID) REFERENCES TIMER(TIMER_ID)
        ON DELETE CASCADE
);

-- 인덱스 생성
CREATE INDEX IDX_TIMER_OWNER_ID ON TIMER(OWNER_ID);
CREATE INDEX IDX_TIMER_TARGET_TIME ON TIMER(TARGET_TIME);
CREATE INDEX IDX_TIMESTAMP_TIMER_ID ON TIMESTAMP(TIMER_ID);

-- UPDATED_AT 컬럼을 자동으로 업데이트하는 트리거 함수 생성
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.UPDATED_AT = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ language 'plpgsql';

-- TIMER 테이블에 트리거 생성
CREATE TRIGGER update_timer_updated_at 
    BEFORE UPDATE ON TIMER 
    FOR EACH ROW 
    EXECUTE FUNCTION update_updated_at_column();